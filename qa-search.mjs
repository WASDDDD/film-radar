import { chromium } from '/root/workspace/run/film-radar-qa/node_modules/playwright/index.mjs';
const base = process.env.BASE || 'http://127.0.0.1:18880';
const q = process.env.Q || '让子弹飞';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text().slice(0, 200)); });
await page.goto(base + '/#search?q=' + encodeURIComponent(q), { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(12000);
const cards = await page.locator('#search-grid > *').count();
const titles = await page.locator('#search-grid > *').evaluateAll(els => els.slice(0, 8).map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 60)));
await page.screenshot({ path: `/storage/emulated/0/Download/DSH-Go/2026-11-21_影视雷达/netlify-search-${q}.png` });
console.log(JSON.stringify({ q, cards, titles, errors }, null, 2));
await browser.close();
